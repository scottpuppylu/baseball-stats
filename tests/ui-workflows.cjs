const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const {chromium} = require('playwright');
const output = process.env.UI_QA_OUTPUT || path.join(os.tmpdir(), 'baseball-ui-qa');
fs.mkdirSync(output, {recursive:true});
let browser;
const contexts = [], results = [];
const url = process.env.UI_PREVIEW_URL || 'http://127.0.0.1:54321';
async function click(page, selector) {
  const target = page.locator(selector).first();
  await target.evaluate(element => element.scrollIntoView({block:'center'}));
  await target.click();
}
async function tab(page, name, mobile) {
  if (mobile) await click(page, '#uiMoreNavigation');
  await click(page, `#btnTab${name}`);
}
async function state(page) { return page.evaluate(() => JSON.parse(localStorage.getItem('rebas_active_game'))); }
(async () => {
  browser = await chromium.connectOverCDP(process.env.UI_CDP_URL || 'http://127.0.0.1:7293');
  for (const [width,height,role,dh] of [[390,844,'先攻',false],[768,1024,'後攻',true],[1440,900,'先攻',true]]) {
    const context = await browser.newContext({viewport:{width,height},hasTouch:width<1024});
    contexts.push(context);
    await context.route(/https:\/\/(api\.github\.com|raw\.githubusercontent\.com)\//, route => route.abort());
    await context.addInitScript(games => localStorage.setItem('rebas_all_games', JSON.stringify(games)), JSON.parse(fs.readFileSync(path.join(__dirname,'..','data','games.json'),'utf8')));
    await context.addInitScript(() => { window.confirm = () => true; window.alert = () => {}; });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(url);
    await page.waitForFunction(() => document.getElementById('uiPageTitle') && document.getElementById('syncStatusBadge').textContent.includes('同步'));
    const mobile = width < 768;
    await tab(page,'Lineup',mobile);
    await click(page,'button[onclick="selectAllAttendance()"]');
    await click(page,dh?'#btnRuleWithDh':'#btnRuleNoDh');
    await click(page,'button[onclick="applyRecommendedToCustom()"]');
    assert.equal(await page.locator('#customLineupPickersContainer select').count(),dh?11:10);
    await tab(page,'Scorebook',mobile);
    await page.locator('#setup_game_date').fill('2026-10-04');
    await page.locator('#setup_game_opponent').fill(`隔離測試-${width}-${role}`);
    await page.locator('#setup_game_role').selectOption(role);
    await click(page,'button[onclick="loadLineupIntoGameSetup(\'custom\')"]');
    assert.equal(await page.locator('#setupLineupGrid select').count(),dh?11:10);
    await click(page,'button[onclick="startNewGameFromSetup()"]');
    let game = await state(page);
    assert.equal(game.lineup.length,dh?11:10);
    assert.equal(game.currentHalf,'top');
    const gameId = game.id;
    if (role === '後攻') await click(page,'button[onclick="switchInningNext()"]');
    await click(page,'button[onclick="recordQuickWalk()"]');
    const beforeRunner = await state(page);
    await click(page,'button[onclick="recordRunnerOut()"]');
    assert.equal((await state(page)).currentBatterIdx,beforeRunner.currentBatterIdx);
    await click(page,'button[onclick="openSubstituteModal()"]');
    const replacement = await page.locator('#substituteNewPlayerSelect option').evaluateAll(options => options.find(option=>option.value && !option.value.startsWith('__')).value);
    await page.locator('#substituteNewPlayerSelect').selectOption(replacement);
    await click(page,'button[onclick="confirmSubstitution()"]');
    assert.equal((await state(page)).substitutions.length,1);
    const field = page.locator('#interactiveFieldSvg');
    await field.evaluate(element => element.scrollIntoView({block:'center'}));
    const fieldBox = await field.boundingBox();
    await field.click({position:{x:fieldBox.width*.3,y:fieldBox.height*.35}});
    await click(page,'#traj_line');
    await click(page,'#res_HR');
    await click(page,'#rbi_2');
    await click(page,'#runs_2');
    await click(page,'button[onclick="submitBattedBallPlay()"]');
    assert.equal((await state(page)).finalScore.us,2);
    await click(page,'#btnInningCloudSync');
    await page.waitForFunction(() => window.__previewWrites.includes('data/games.json'));
    // Rotate while scoring: the full local state must survive intact.
    const saved = await state(page);
    await page.setViewportSize({width:height,height:width});
    assert.deepEqual(await state(page),saved);
    await page.setViewportSize({width,height});
    await click(page,'button[onclick="switchInningNext()"]');
    await page.evaluate(() => openPitcherChangeModal());
    await page.locator('#pitcherModePitchOnly').check();
    await click(page,'button[onclick="confirmPitcherChange()"]');
    assert.equal((await state(page)).substitutions.length,1);
    await page.evaluate(() => openPitcherChangeModal());
    await page.locator('#pitcherModeReplace').check();
    await click(page,'button[onclick="confirmPitcherChange()"]');
    assert.equal((await state(page)).substitutions.length,2);
    await click(page,'button[onclick="recordDefenseEvent(\'GO\')"]');
    await click(page,'button[onclick="recordDefenseEvent(\'HIT\')"]');
    await click(page,'button[onclick="recordDefenseEvent(\'RUN\', 1)"]');
    await click(page,'button[onclick="recordDefenseEvent(\'DP\')"]');
    game = await state(page);
    assert.equal(game.currentOuts,3);
    assert.equal(game.finalScore.opp,1);
    await page.screenshot({path:path.join(output,`${width}-LiveDefense.png`)});
    await click(page,'button[onclick="finishActiveGameAndSyncLogs()"]');
    await page.waitForFunction(() => localStorage.getItem('rebas_active_game') === null);
    await page.locator('#reviewGameSelect').selectOption(gameId);
    await click(page,'button[onclick="toggleEditCurrentReviewGame()"]');
    await page.locator('#editGameOpponent').fill(`覆盤修改-${width}`);
    await page.evaluate(() => { window.__previewFailWrites = true; });
    await click(page,'button[onclick^="saveEditedReviewGame("]');
    await page.waitForFunction(() => document.querySelector('#globalToastContainer')?.textContent.includes('尚未完整同步'));
    assert.ok(await page.locator('#editGameOpponent').isVisible());
    await page.evaluate(() => { window.__previewFailWrites = false; });
    await click(page,'button[onclick^="saveEditedReviewGame("]');
    await page.waitForFunction(() => !document.querySelector('#editGameOpponent'));
    assert.match(await page.locator('#reviewGameSelect').textContent(),new RegExp(`覆盤修改-${width}`));
    await page.screenshot({path:path.join(output,`${width}-Review.png`)});
    await click(page,'#btnScoreSubSpray');
    const point = page.locator('#sprayPointsContainer circle').first();
    await point.evaluate(element => element.scrollIntoView({block:'center'}));
    await point.click({force:true});
    assert.ok(await page.locator('.ui-touch-detail').isVisible());
    await click(page,'.ui-touch-detail button');
    assert.deepEqual(errors,[],`${width} workflow runtime errors`);
    results.push({width,height,role,dh,passed:['recommended-custom-lineup','start-game','walk','runner-out-batter-preserved','substitution','field-hit-rbi-score','inning-sync','rotate-state-preserved','pitch-only','pitcher-replace-slot','defense-events','finish-sync','review-edit-failure-retry','touch-spray-detail']});
    await context.close();
  }
  fs.writeFileSync(path.join(output,'workflow-report.json'),JSON.stringify(results,null,2));
  console.log(JSON.stringify({workflows:results.length,checks:results.reduce((sum,result)=>sum+result.passed.length,0),output}));
  await browser.close();
})().catch(async error => {
  console.error(error.stack);
  for (const context of contexts) for (const page of context.pages()) await page.screenshot({path:path.join(output,'workflow-failure.png')}).catch(()=>{});
  await Promise.allSettled(contexts.map(context=>context.close()));
  await browser?.close();
  process.exitCode=1;
});
