  function dateOf(v) {
    let m = /^v(\d{2})(\d{2})(\d{2})\.(\d{2})(\d{2})$/.exec(v);
    if (m) return `20${m[1]}/${m[2]}/${m[3]} ${m[4]}:${m[5]}`;
    m = /^v(\d{2})(\d{2})\.(\d{2})(\d{2})$/.exec(v);
    return m ? `20${m[1]}/${m[2]}/01 ${m[3]}:${m[4]}` : '';
  }
