// Prebuilds the site's Tailwind CSS (vendor/tailwind-site.css) so phones no longer run the Tailwind Play compiler, which
// watched every DOM change and regenerated styles (most of the scroll-time CPU on phones). Every class-like token in the
// page and its scripts is handed to the same Tailwind 3.4.17 Play build in a headless browser, and the CSS it generates is
// saved. The site uses no dynamically assembled class names (tests/tailwind-static.test.cjs checks), so nothing is missed.
//   node scripts/build-tailwind.cjs
const fs = require('node:fs');
const path = require('node:path');
const {chromium} = require('playwright');

const root = path.resolve(__dirname, '..');
const SOURCES = ['index.html', ...fs.readdirSync(root).filter(f => f.endsWith('.js'))];
function tokens() {
  const set = new Set();
  for (const file of SOURCES) {
    const text = fs.readFileSync(path.join(root, file), 'utf8');
    for (const raw of text.split(/[\s"'`<>=;{}\\]+/)) {
      const t = raw.replace(/^[(,]+|[),.]+$/g, '');
      if (t.length > 1 && t.length < 90 && /^!?-?[a-z@][\w\-:/.[\]#%,()!+]*$/i.test(t)) set.add(t);
    }
  }
  return [...set];
}

async function main() {
  const list = tokens();
  const play = fs.readFileSync(path.join(root, 'vendor/tailwindcss-play-3.4.17.js'), 'utf8');
  const browser = await chromium.launch({channel: process.env.PW_CHANNEL || 'chrome'});
  const page = await browser.newPage();
  await page.setContent(`<!doctype html><html><head><script>${play.replace(/<\/script/gi, '<\\/script')}</script></head><body></body></html>`);
  await page.evaluate(classes => {
    const holder = document.createElement('div');
    holder.className = classes.join(' ');
    document.body.append(holder);
  }, list);
  await page.waitForFunction(() => [...document.querySelectorAll('style')].some(s => s.textContent.includes('--tw-border-spacing-x')), null, {timeout: 30000});
  await page.waitForTimeout(800); // let the observer settle on the final set
  const css = await page.evaluate(() => [...document.querySelectorAll('style')].map(s => s.textContent).find(t => t.includes('--tw-border-spacing-x')));
  await browser.close();
  const header = '/* Generated by scripts/build-tailwind.cjs from Tailwind CSS 3.4.17 (MIT License). Do not edit; rebuild after changing classes. */\n';
  fs.writeFileSync(path.join(root, 'vendor/tailwind-site.css'), header + css);
  console.log(JSON.stringify({tokens: list.length, bytes: css.length}));
}
main().catch(error => { console.error(error); process.exitCode = 1; });
